"""
build_backend_config.py
=======================
Paper-v2 task T4.1: writes backend/config/final_config.json. Every value is
copied from results/manifest.json and carries the manifest key it came from, so
the running backend cites its evidence. The deployed engine is the dataset-42
model (evaluation/artifacts), so dataset-42 settings are used; the multi-dataset
keys named in "evidence" justify the CHOICE of each component.

    python -m tools.build_backend_config
"""
from __future__ import annotations

import json

from tools.manifest import PROJECT_ROOT, load

OUT = PROJECT_ROOT / "backend" / "config" / "final_config.json"


def main() -> None:
    e = load()["entries"]

    def v(key):
        return {"value": e[key]["value"], "source": key, "run_id": e[key]["run_id"]}

    cfg = {
        "_note": "Generated by tools/build_backend_config.py from results/manifest.json. Do not edit by hand.",
        "anomaly": {"alpha": v("anomaly.s42.tuning.alpha"), "tau_flag": v("anomaly.s42.tuning.tau_hybrid")},
        "enforcement": {
            "form": {"value": "gated", "source": "fusion.summary.gated.threat_recall.mean",
                     "reason": "highest threat recall at the same benign budget across 10 datasets (T2.5); "
                               "escalates high-anomaly sessions regardless of content sensitivity"},
            "beta": v("fusion.ds42.gated.params.beta"),
            "tau_A": v("fusion.ds42.gated.params.tau_A"),
            "t_alert": v("fusion.ds42.gated.t_alert"),
            "t_block": v("fusion.ds42.gated.t_block"),
        },
        "drift": {
            "detector": {"value": "cusum", "source": "drift.summary.cusum.hybrid_or_drift.malicious_episode_recall.mean",
                         "reason": "raises malicious-insider episode recall 0.133 -> 0.567 (T2.4); costs FPR 0.25 -> 0.80 percent"},
            "k": v("drift.ds42.cusum.k"), "h": v("drift.ds42.cusum.h"),
            "action_on_alarm": {"value": "ALERT", "source": "design choice (D-018): review, do not auto-block"},
        },
        "pii": {
            "text_recognisers": {"value": "presidio_plus", "source": "pii2.v2.branch1.presidio_plus.all.f1"},
        },
    }
    taus = sorted(k for k in e if k.startswith("pii2.v2.cascade.") and k.endswith(".calib_tau"))
    if taus:
        cfg["pii"]["tau_ocr"] = [v(k) for k in taus]
    dep = "pii2.v2.cascade.easyocr_cpu.gemma-3-4b-it.calib_tau"
    if dep in e:
        # the proxy's Tier 2 runs EasyOCR and the best local VLM is gemma-3-4b-it (T3.3)
        cfg["pii"]["tau_ocr_deployed"] = {**v(dep), "reason": "Tier 2 uses EasyOCR; gemma-3-4b-it is the best local VLM "
                                                       "(T3.3). Chosen on calib documents; routes almost every image "
                                                       "to the VLM (N-049)"}
    cut = "latency_cutoff.chosen_bytes"
    if cut in e:
        # F12 (D-035): largest calibrated text size whose Tier 1 server p95 meets the 100 ms budget
        cfg["tier1"] = {"max_text_bytes": {**v(cut), "reason": "text above this size is scanned in Tier 2 (D-035)"}}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(cfg, indent=1), encoding="utf-8")
    print(f"  -> {OUT}")


if __name__ == "__main__":
    main()
