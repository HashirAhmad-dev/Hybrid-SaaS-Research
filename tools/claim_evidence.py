"""
claim_evidence.py
=================
Builds docs/CLAIM_EVIDENCE.md and paper_inputs/numbers.json from the claims files
in results/claims/ and the run metadata in results/manifest.json:

    claim -> manifest key -> value -> script -> seeds -> run id / date / git hash

Every row is checked first with tools/check_numbers.py logic; a failing claim
stops the build.

    python -m tools.claim_evidence
"""
from __future__ import annotations

import json
from pathlib import Path

from tools.check_numbers import check, parse_claims
from tools.manifest import PROJECT_ROOT, load

CLAIMS = PROJECT_ROOT / "results" / "claims"
DOC = PROJECT_ROOT / "docs" / "CLAIM_EVIDENCE.md"
NUMBERS = PROJECT_ROOT / "paper_inputs" / "numbers.json"


def main() -> None:
    m = load()
    entries, runs = m["entries"], m["runs"]
    lines = ["# CLAIM_EVIDENCE.md", "",
             "Generated by `python -m tools.claim_evidence`. Do not edit by hand.",
             "Each row: the claim as worded in a claims file, the manifest key that holds the number,",
             "the value, the script that produced it, the seeds, and the run that recorded it.",
             "Every row passed `tools/check_numbers.py` when this file was generated.", ""]
    numbers = {}
    for f in sorted(CLAIMS.glob("*.claims")):
        claims = parse_claims(f.read_text(encoding="utf-8").splitlines(), str(f))
        rows = check(claims, entries)
        bad = [r for r in rows if not r["ok"]]
        if bad:
            raise SystemExit(f"{f}: {len(bad)} claims fail; run tools/check_numbers.py")
        lines += [f"## {f.stem}", "", "| Claim | Manifest key | Value | Script | Seeds | Run |",
                  "|---|---|---|---|---|---|"]
        for r in rows:
            run = runs.get(r["run_id"], {})
            prefix = max((p for p in run.get("prefixes", []) if r["key"].startswith(p)), key=len, default="")
            script = run.get("scripts", {}).get(prefix, run.get("script", ""))
            seeds = json.dumps(run.get("seeds", {})).replace("|", "/")
            gh = (run.get("git_hash") or "")[:8]
            lines.append(f"| {r['label']} | `{r['key']}` | {r['written']} | `{script}` | {seeds} | "
                         f"{r['run_id']} ({gh}) |")
            numbers[r["key"]] = {"value": r["manifest"], "as_written": r["written"], "claim": r["label"],
                                 "script": script, "run_id": r["run_id"], "git_hash": run.get("git_hash")}
        lines.append("")
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    NUMBERS.parent.mkdir(parents=True, exist_ok=True)
    NUMBERS.write_text(json.dumps(numbers, indent=1, sort_keys=True), encoding="utf-8")
    print(f"{len(numbers)} numbers -> {DOC} and {NUMBERS}")


if __name__ == "__main__":
    main()
